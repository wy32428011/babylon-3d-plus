import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';
const output=path.resolve('output/geographic-opening');
const url=pathToFileURL(path.join(output,'geographic-opening-demo.html')).href;
const browser=await chromium.launch({channel:'chrome',headless:true});
const checks=[],errors=[];
try{
 const page=await browser.newPage({viewport:{width:1280,height:720}});
 page.setDefaultTimeout(30000);page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url+'?seek=4');await page.waitForFunction(()=>window.__openingDemo?.getState().ready);
 const saved=await page.evaluate(()=>JSON.parse(JSON.stringify(window.__openingDemo.settings)));
 const camera=await page.evaluate(()=>Array.from(window.__openingDemo.scene.activeCamera.getViewMatrix(true).m));
 await page.locator('[data-action="fullscreen"]').click();
 await page.waitForFunction(()=>document.fullscreenElement===document.body);
 await page.evaluate(()=>window.__openingDemo.seek(61.6));
 assert.equal(await page.evaluate(()=>document.fullscreenElement?.contains(document.querySelector('#renderCanvas'))),true);
 await page.evaluate(()=>{document.querySelector('[data-action="enter"]').click();document.querySelector('[data-action="play"]').click();document.querySelector('[data-action="restart"]').click();});
 await page.waitForFunction(()=>document.querySelector('.geographic-opening-host')===null);
 assert.equal(await page.evaluate(()=>document.fullscreenElement===document.body),true);
 await page.evaluate(()=>document.exitFullscreen());
 checks.push('全屏包含真实业务canvas，淡出时场景仍在全屏内','跳过途中暂停和重播不会阻塞清理');
 await page.evaluate(settings=>{window.__openingDemo.configure({...settings,allowSkip:false});window.__openingDemo.pause();},saved);
 await page.waitForFunction(()=>window.__openingDemo.getState().ready);
 await page.evaluate(()=>window.__openingDemo.seek(20));
 assert.equal(await page.locator('[data-role="progress"]').isDisabled(),true);
 assert.equal(await page.locator('[data-stage="8"]').isDisabled(),true);
 await page.evaluate(()=>{const p=document.querySelector('[data-role="progress"]');p.value='62';p.dispatchEvent(new Event('input',{bubbles:true}));});
 assert.equal(await page.evaluate(()=>window.__openingDemo.getState().snapshot.elapsedSeconds),20);
 checks.push('禁止跳过时章节和进度不能绕过播放');
 await page.evaluate(settings=>{window.__openingDemo.configure(settings);window.__openingDemo.pause();window.__openingDemo.seek(4);},saved);
 await page.waitForFunction(()=>window.__openingDemo.getState().ready);
 await page.evaluate(()=>document.querySelector('canvas.zd-globe').getContext('webgl').getExtension('WEBGL_lose_context').loseContext());
 await page.waitForFunction(()=>!!document.querySelector('canvas.zd-globe')?.getContext('2d'));
 await page.screenshot({path:path.join(output,'reference-software-fallback.png')});
 await page.evaluate(()=>window.__openingDemo.skip());await page.waitForFunction(()=>!document.querySelector('.geographic-opening-host'));
 checks.push('开场独立WebGL丢失后软件球面继续，退出释放资源');
 await page.evaluate(settings=>window.__openingDemo.configure({...settings,reference:{...settings.reference,stageDurations:[.2,.2,0,.2,.2,0,.2,.2,.2]}}),saved);
 await page.waitForFunction(()=>window.__openingDemo.getState().snapshot.phase==='complete');
 assert.deepEqual(await page.evaluate(()=>Array.from(window.__openingDemo.scene.activeCamera.getViewMatrix(true).m)),camera);
 assert.equal(await page.locator('.geographic-opening-host').count(),0);
 checks.push('自然播放完成交接而非仅人工寻帧，相机保持');
 const fail=await browser.newPage({viewport:{width:1280,height:720}});fail.setDefaultTimeout(30000);
 fail.on('pageerror',e=>errors.push(e.message));
 await fail.addInitScript(()=>{
  const original=Object.getOwnPropertyDescriptor(HTMLImageElement.prototype,'src');
  Object.defineProperty(HTMLImageElement.prototype,'src',{configurable:true,get:original.get,set(value){if(String(value).startsWith('data:image/webp')){queueMicrotask(()=>this.dispatchEvent(new Event('error')));}else original.set.call(this,value);}});
 });
 await fail.goto(url);await fail.waitForFunction(()=>window.__openingDemo?.getState().error);
 assert.match(await fail.evaluate(()=>window.__openingDemo.getState().error),/加载失败/);
 assert.equal(await fail.locator('.geographic-opening-host').count(),0);
 assert.equal(await fail.evaluate(()=>window.__openingDemo.engine.scenes.length),1);
 checks.push('素材失败有诊断并释放开场覆盖，不挂住业务场景');
 assert.deepEqual(errors,[]);
 await writeFile(path.join(output,'reference-lifecycle-verification.json'),JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors},null,2));
}finally{await browser.close();}
